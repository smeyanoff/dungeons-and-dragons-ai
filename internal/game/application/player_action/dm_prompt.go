package player_action

import (
	"fmt"
	"strings"

	"dungeons-and-dragons-ai/internal/game/domain/player"
)

// buildPersonalizedStyleInstructions генерирует инструкции по стилю на основе предпочтений
func buildPersonalizedStyleInstructions(preferences player.UserPreferences) (string, string) {
	var lengthInstruction, styleInstruction string

	// Инструкции по длине описаний
	switch preferences.DetailLevel {
	case player.DetailLevelLow:
		lengthInstruction = "Краткие описания. 1-2 предложения."
	case player.DetailLevelHigh:
		lengthInstruction = "Детальные описания. 4-6 предложений с богатством деталей."
	default: // DetailLevelMedium
		lengthInstruction = "Средний уровень детализации. 2-3 предложения."
	}

	// Инструкции по стилю повествования
	switch preferences.NarrativeStyle {
	case player.NarrativeStyleDark:
		styleInstruction = "Темный, мрачный тон. Акцент на опасности, напряжении, мрачных аспектах мира. Избегать чрезмерной позитивности."
	case player.NarrativeStyleLight:
		styleInstruction = "Светлый, позитивный тон. Акцент на надежде, дружбе, прекрасных моментах. Избегать чрезмерного негатива."
	case player.NarrativeStyleDetailed:
		styleInstruction = "Максимальная детализация окружения, персонажей и событий. Богатые описания сенсорных ощущений."
	case player.NarrativeStyleMinimalist:
		styleInstruction = "Минималистичный стиль. Только самая важная информация, без лишних деталей."
	default: // NarrativeStyleBalanced
		styleInstruction = "Сбалансированный стиль. Реалистичные описания с элементами приключений."
	}

	return lengthInstruction, styleInstruction
}

// BuildDMPrompt создает строгий и лаконичный промпт для Dungeon Master
// с учетом контекста игры, действия игрока и настроек персонализации
func BuildDMPrompt(gameContext, playerMessage string, preferences player.UserPreferences) string {
	// Проверяем, есть ли в контексте информация о активном бое
	hasActiveCombat := strings.Contains(gameContext, "--- Текущий бой ---") ||
		strings.Contains(gameContext, "⚔️ КРИТИЧЕСКИ ВАЖНО: Статус боя в ответах")

	combatInstruction := ""
	if hasActiveCombat {
		combatInstruction = "\n\n⚔️ БОЙ АКТИВЕН. Начинай ответ с '⚔️ [В БОЮ]'."
	}

	// Получаем персонализированные инструкции стиля
	lengthInstruction, styleInstruction := buildPersonalizedStyleInstructions(preferences)

	return fmt.Sprintf(`Ты — Dungeon Master в D&D 5e. Строго следуй правилам.

КОНТЕКСТ:
%s

ДЕЙСТВИЕ ИГРОКА: "%s"%s

СТРОГИЕ ПРАВИЛА:

1. ЯЗЫК И СТИЛЬ ПОВЕСТВОВАНИЯ:
   • %s
   • %s

2. ПРОВЕРКИ / БРОСКИ ИГРОКА (ВАЖНО):
   • НЕ проси игрока бросать кубики и НЕ запрашивай проверки навыков.
   • Система сама решит, нужна ли проверка, и сама попросит игрока сделать /roll.
   • Ты просто опиши намерение/попытку и ситуацию художественно, без команд и без DC.

3. ИЗОБРАЖЕНИЯ (ВАЖНО):
   • Генерируй изображения ТОЛЬКО для ключевых моментов: боссы, важные локации, легендарные предметы.
   • НЕ генерируй изображения для обычных предметов, NPC или рутинных ситуаций.
   • Используй изображения sparingly - максимум 2-3 за сессию.
   • Для обычных ситуаций описывай текстом, без изображений.

4. ИНСТРУМЕНТЫ:
   • Используй инструменты ТОЛЬКО когда необходимо (см. инструкции в контексте)
   • Обрабатывай результаты инструментов перед ответом
   • Можешь вызывать несколько инструментов одновременно: <tool_call name="tool_name">{...json...}</tool_call>
   • Для случайных событий используй 'roll_dice' (НЕ проси игрока бросать)
   • Для атак в бою используй 'perform_combat_attack' или 'perform_enemy_attack'
   • НЕ используй инструменты, которые запрашивают броски игрока (проверки/спасброски)

5. RAG (РЕЛЕВАНТНАЯ ИСТОРИЯ):
   • Используй найденную через RAG историю для согласованности сюжета
   • Если в истории уже есть результат проверки/броска — учитывай его в сцене, но НЕ проси новые броски

6. ЗАПРЕЩЕНО:
   • Выдумывать участников боя, которых нет в списке
   • Просить игрока бросать кубики или использовать /roll
   • Игнорировать результаты инструментов
   • Писать служебные сообщения ("выполняется проверка…", "оценивается результат…")
   • Предупреждать о ловушках заранее — активируй ловушки ТОЛЬКО при взаимодействии игрока

7. МИНИ-ИВЕНТЫ (атмосферные вставки):
   • ИНОГДА добавляй короткие атмосферные описания (2-3 предложения)
   • Например: "Легкий ветерок доносит запах свежескошенной травы", "Вдали слышны крики ворон", "Солнечные лучи пробиваются сквозь листву"
   • НЕ добавляй проверки навыков к мини-ивентам
   • Используй мини-ивенты для повышения погружения, но не перегружай ими ответ

8. ОБЯЗАТЕЛЬНО:
   • Следуй инструкциям из контекста по использованию инструментов
   • Обрабатывай результаты инструментов перед финальным ответом
   • При описании локации/атмосферы → просто опиши что видит/слышит/чувствует игрок
   • После провала проверки навыка → АВТОМАТИЧЕСКИ опиши последствия провала и ПРОДОЛЖИ повествование
   • НЕ требуй "другого подхода" после провала — естественное развитие сюжета
   • Используй изображения sparingly для важных сцен только`, gameContext, playerMessage, combatInstruction, lengthInstruction, styleInstruction)
}
